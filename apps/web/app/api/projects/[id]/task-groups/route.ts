import { NextResponse } from 'next/server';
import { todoActionSchema } from '@paperworking/validation';
import { updateProjectInStore } from '@/lib/projects/project-store';
import {
  filterTaskListsForGuest,
  filterTasksForGuest,
  guestForbidden,
  newProjectItemId,
  parseProjectBody,
  projectApiError,
  resolveActorIdentity,
  resolveProjectAccess,
  type ProjectAccess,
} from '@/lib/projects/project-access';
import { recordProjectActivity } from '@/lib/projects/activity';
import type { AcquisitionTask, ProjectTaskList } from '@/lib/projects/types';

/**
 * To-do lists over the project's single `tasks` store.
 * GET  -> { taskLists, tasks }   (guests: shared tasks and the lists that contain them)
 * POST -> actions create_list | add_task | add_subtask | toggle_task | toggle_subtask
 */

function visibleTodos(access: ProjectAccess, taskLists: ProjectTaskList[], tasks: AcquisitionTask[]) {
  if (access.kind === 'team') return { taskLists, tasks };
  const shared = filterTasksForGuest(tasks);
  return { taskLists: filterTaskListsForGuest(taskLists, shared), tasks: shared };
}

export async function GET(
  _request: Request,
  context: { params: Promise<{ id: string }> },
) {
  const { id: projectId } = await context.params;
  const access = await resolveProjectAccess(projectId, 'viewer');
  if (!access.ok) return access.response;

  return NextResponse.json(visibleTodos(access, access.project.taskLists ?? [], access.project.tasks ?? []));
}

export async function POST(
  request: Request,
  context: { params: Promise<{ id: string }> },
) {
  const { id: projectId } = await context.params;
  const access = await resolveProjectAccess(projectId, 'member');
  if (!access.ok) return access.response;

  const parsed = await parseProjectBody(request, todoActionSchema);
  if (!parsed.ok) return parsed.response;
  const body = parsed.data;

  const isGuest = access.kind === 'guest';
  if (isGuest && body.action !== 'toggle_task' && body.action !== 'toggle_subtask') {
    return guestForbidden();
  }

  const { project } = access;
  const taskLists: ProjectTaskList[] = structuredClone(project.taskLists ?? []);
  const tasks: AcquisitionTask[] = structuredClone(project.tasks ?? []);
  const actor = resolveActorIdentity(access);
  const now = new Date().toISOString();

  const persist = async (activity: { kind: string; summary: string; targetId: string; vendorVisible: boolean }) => {
    await updateProjectInStore(projectId, { taskLists, tasks });
    await recordProjectActivity(projectId, { actorUid: access.uid, actorName: actor.name, ...activity });
    return visibleTodos(access, taskLists, tasks);
  };

  // Guests may only touch shared tasks; anything else is reported as missing.
  const findTask = (taskId: string) => {
    const task = tasks.find((t) => t.id === taskId);
    if (!task || (isGuest && task.vendorVisible !== true)) return undefined;
    return task;
  };

  switch (body.action) {
    case 'create_list': {
      const list: ProjectTaskList = {
        id: newProjectItemId('tl'),
        title: body.title,
        phase: body.phase ?? project.currentPhase ?? 'acquisition',
        createdAt: now,
      };
      taskLists.push(list);
      const view = await persist({
        kind: 'todo.list_created',
        summary: `Created to-do list "${list.title}"`,
        targetId: list.id,
        vendorVisible: false,
      });
      return NextResponse.json({ success: true, list, ...view }, { status: 201 });
    }

    case 'add_task': {
      const list = taskLists.find((l) => l.id === body.listId);
      if (!list) return projectApiError(404, 'To-do list not found', 'NOT_FOUND');

      let assignee: { uid: string; name: string } | undefined;
      if (body.assigneeId) {
        const member = (project.teamMembers ?? []).find(
          (m: { uid?: string; id?: string }) => m && (m.uid === body.assigneeId || m.id === body.assigneeId),
        ) as { uid?: string; id?: string; name?: string } | undefined;
        if (!member) {
          return projectApiError(400, 'Assignee must be a member of this project team', 'INVALID_ASSIGNEE');
        }
        assignee = { uid: member.uid ?? member.id ?? body.assigneeId, name: member.name ?? 'Unknown member' };
      }

      const task: AcquisitionTask = {
        id: newProjectItemId('tsk'),
        projectId,
        title: body.title,
        listId: list.id,
        ...(body.dueDate ? { dueDate: body.dueDate } : {}),
        status: 'pending',
        isAutoGenerated: false,
        ...(assignee ? { assigneeUid: assignee.uid, assigneeName: assignee.name } : {}),
        ...(body.notes ? { notes: body.notes } : {}),
        vendorVisible: Boolean(body.vendorVisible),
        ...(body.linkedDocumentId ? { linkedDocumentId: body.linkedDocumentId } : {}),
        subtasks: [],
        phase: list.phase,
      };
      tasks.push(task);
      const view = await persist({
        kind: 'todo.task_created',
        summary: `Added "${task.title}" to "${list.title}"${assignee ? `, assigned to ${assignee.name}` : ''}`,
        targetId: task.id,
        vendorVisible: Boolean(task.vendorVisible),
      });
      return NextResponse.json({ success: true, task, ...view }, { status: 201 });
    }

    case 'update_task': {
      const task = findTask(body.taskId);
      if (!task) return projectApiError(404, 'Task not found', 'NOT_FOUND');

      if (body.title !== undefined) task.title = body.title;
      if (body.dueDate !== undefined) task.dueDate = body.dueDate;
      if (body.notes !== undefined) task.notes = body.notes;
      if (body.vendorVisible !== undefined) task.vendorVisible = Boolean(body.vendorVisible);
      if (body.linkedDocumentId !== undefined) task.linkedDocumentId = body.linkedDocumentId;

      if (body.assigneeId !== undefined) {
        if (!body.assigneeId) {
          delete task.assigneeUid;
          delete task.assigneeName;
        } else {
          const member = (project.teamMembers ?? []).find(
            (m: { uid?: string; id?: string }) => m && (m.uid === body.assigneeId || m.id === body.assigneeId),
          ) as { uid?: string; id?: string; name?: string } | undefined;
          if (!member) {
            return projectApiError(400, 'Assignee must be a member of this project team', 'INVALID_ASSIGNEE');
          }
          task.assigneeUid = member.uid ?? member.id ?? body.assigneeId;
          task.assigneeName = member.name ?? 'Unknown member';
        }
      }

      const view = await persist({
        kind: 'todo.task_updated',
        summary: `Updated to-do "${task.title}"`,
        targetId: task.id,
        vendorVisible: Boolean(task.vendorVisible),
      });
      return NextResponse.json({ success: true, task, ...view }, { status: 200 });
    }

    case 'attach_document': {
      const task = findTask(body.taskId);
      if (!task) return projectApiError(404, 'Task not found', 'NOT_FOUND');

      const doc = (project.documents ?? []).find((d) => d.doc_id === body.documentId);
      task.linkedDocumentId = body.documentId;

      const view = await persist({
        kind: 'todo.document_attached',
        summary: `Attached "${doc?.name ?? body.documentId}" to "${task.title}"`,
        targetId: task.id,
        vendorVisible: Boolean(task.vendorVisible),
      });
      return NextResponse.json({ success: true, task, ...view }, { status: 200 });
    }

    case 'add_subtask': {
      const task = findTask(body.taskId);
      if (!task) return projectApiError(404, 'Task not found', 'NOT_FOUND');
      const subtask = { id: newProjectItemId('sub'), title: body.title, completed: false };
      task.subtasks = [...(task.subtasks ?? []), subtask];
      const view = await persist({
        kind: 'todo.subtask_created',
        summary: `Added subtask "${subtask.title}" to "${task.title}"`,
        targetId: task.id,
        vendorVisible: Boolean(task.vendorVisible),
      });
      return NextResponse.json({ success: true, subtask, task, ...view }, { status: 201 });
    }

    case 'toggle_task': {
      const task = findTask(body.taskId);
      if (!task) return projectApiError(404, 'Task not found', 'NOT_FOUND');
      const completing = task.status !== 'complete';
      task.status = completing ? 'complete' : 'pending';
      if (completing) {
        task.completedAt = now;
        task.completedByUid = access.uid;
      } else {
        task.completedAt = null;
        delete task.completedByUid;
      }
      const view = await persist({
        kind: 'todo.task_toggled',
        summary: `${completing ? 'Completed' : 'Reopened'} "${task.title}"`,
        targetId: task.id,
        vendorVisible: Boolean(task.vendorVisible),
      });
      return NextResponse.json({ success: true, task, ...view });
    }

    case 'toggle_subtask': {
      const task = findTask(body.taskId);
      const subtask = task?.subtasks?.find((s) => s.id === body.subtaskId);
      if (!task || !subtask) return projectApiError(404, 'Subtask not found', 'NOT_FOUND');
      subtask.completed = !subtask.completed;
      const view = await persist({
        kind: 'todo.subtask_toggled',
        summary: `${subtask.completed ? 'Checked off' : 'Unchecked'} "${subtask.title}" on "${task.title}"`,
        targetId: task.id,
        vendorVisible: Boolean(task.vendorVisible),
      });
      return NextResponse.json({ success: true, task, ...view });
    }
  }
}
