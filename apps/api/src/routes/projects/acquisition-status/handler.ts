import { jsonResponse, type RouteResult } from "../../../http/response.js";
import type { RequireAuthFn } from "../../../lib/auth/auth-types.js";
import { isAuthFailure } from "../../../lib/auth/auth-types.js";
import { requireOrgRole, recordAuthzAuditEvent } from "../../../lib/auth/require-role.js";
import {
  validateAcquisitionTransition,
  executeAcquisitionTransition,
  type AcquisitionTransitionContext,
} from "../../../lib/reil/acquisition-state-machine.js";
import type { AcquisitionPipelineStatus } from "@paperworking/validation";

export type GetProjectForAcquisitionStatusFn = (
  projectId: string,
) => Promise<Record<string, unknown> | null>;

export type UpdateProjectAcquisitionStatusFn = (
  projectId: string,
  updates: Record<string, unknown>,
) => Promise<Record<string, unknown>>;

export interface ProjectAcquisitionStatusPatchDeps {
  requireAuth?: RequireAuthFn;
  getProject?: GetProjectForAcquisitionStatusFn;
  updateProject?: UpdateProjectAcquisitionStatusFn;
  scheduleAlerts?: (
    projectId: string,
    contingencies: any[],
    projectAddress?: string,
    ianaTimezone?: string,
  ) => Promise<void>;
}

export interface AcquisitionStatusPatchBody extends AcquisitionTransitionContext {
  targetStatus: AcquisitionPipelineStatus;
}

/**
 * PATCH /api/projects/:id/acquisition-status
 * Updates project acquisition pipeline stage with state machine guard verification,
 * dead reason persistence, and automated milestone task generation on "under_contract".
 */
export async function handleProjectAcquisitionStatusPatch(
  projectId: string,
  body: unknown,
  deps: ProjectAcquisitionStatusPatchDeps = {},
): Promise<RouteResult> {
  try {
    if (!deps.requireAuth) {
      return jsonResponse(500, { error: "Auth not configured" });
    }

    const auth = await deps.requireAuth();
    if (isAuthFailure(auth)) {
      return jsonResponse(auth.status, auth.body);
    }

    if (!body || typeof body !== "object") {
      return jsonResponse(400, { error: "Invalid request body" });
    }

    const patchBody = body as AcquisitionStatusPatchBody;
    const targetStatus = patchBody.targetStatus;
    if (!targetStatus) {
      return jsonResponse(400, { error: "targetStatus is required" });
    }

    if (!deps.getProject) {
      return jsonResponse(500, { error: "Project getter not configured" });
    }

    const project = await deps.getProject(projectId);
    if (!project) {
      return jsonResponse(404, { error: "Project not found" });
    }

    const userOrg = (auth as any).organizationId;
    const projectOrg = (project as any).organizationId;
    if (projectOrg && userOrg && projectOrg !== userOrg) {
      return jsonResponse(403, { error: "Forbidden" });
    }
    let callerRole = 'admin';
    if (projectOrg) {
      const roleCheck = await requireOrgRole(auth, projectOrg, 'admin');
      if (!roleCheck.ok) {
        return jsonResponse(roleCheck.status, roleCheck.body);
      }
      callerRole = roleCheck.role;
    }

    const currentStatus = (project.acquisitionStatus as AcquisitionPipelineStatus) ?? "lead";

    const transitionContext: AcquisitionTransitionContext = {
      ...patchBody,
      projectId,
      contingencies: (project.contingencies as any) ?? [],
    };

    const validation = validateAcquisitionTransition(
      currentStatus,
      targetStatus,
      transitionContext,
    );

    if (!validation.valid) {
      return jsonResponse(422, {
        error: validation.error,
        code: validation.code,
      });
    }

    const transitionResult = executeAcquisitionTransition(
      currentStatus,
      targetStatus,
      transitionContext,
      auth.uid,
    );

    const updates: Record<string, unknown> = {
      acquisitionStatus: transitionResult.updatedStatus,
      status: transitionResult.updatedStatus === "closed" ? "fund" : "acquisition",
      updatedAt: new Date().toISOString(),
    };

    if (transitionResult.deadRecord) {
      updates.deadRecord = transitionResult.deadRecord;
      updates.isArchived = true;
    }

    if (transitionResult.autoGeneratedTasks && transitionResult.autoGeneratedTasks.length > 0) {
      const existingTasks = Array.isArray(project.tasks) ? project.tasks : [];
      updates.tasks = [...existingTasks, ...transitionResult.autoGeneratedTasks];
    }

    // Append to status audit history
    const existingHistory = Array.isArray(project.statusHistory) ? project.statusHistory : [];
    updates.statusHistory = [...existingHistory, transitionResult.transitionLogEntry];

    if (patchBody.closingDate) {
      updates.closingDate = patchBody.closingDate;
    }
    if (patchBody.actualCashToClose !== undefined) {
      updates.actualCashToClose = patchBody.actualCashToClose;
    }
    if (patchBody.closingDocuments && Array.isArray(patchBody.closingDocuments)) {
      const existingDocs = Array.isArray(project.documents) ? project.documents : [];
      const newDocs = patchBody.closingDocuments.map((doc: any, i: number) => ({
        doc_id: doc.doc_id || doc.id || `doc-close-${Date.now()}-${i}`,
        type: doc.type || 'Closing Statement',
        name: doc.name || 'ALTA_Settlement_Statement_Executed.pdf',
        url: doc.url || doc.documentUrl || `/api/projects/${projectId}/documents/closing-${Date.now()}`,
        generated_at: doc.generated_at || doc.uploadedAt || new Date().toISOString(),
      }));
      updates.documents = [...existingDocs, ...newDocs];
    }
    if (patchBody.emdAmount !== undefined) {
      updates.earnestMoney = {
        amount: patchBody.emdAmount,
        status: "deposited",
        holder: patchBody.emdHolder || "Heritage Escrow Co",
        dueDate: patchBody.emdDueDate || new Date(Date.now() + 3 * 86400000).toISOString(),
        depositedAt: new Date().toISOString(),
      };
    }
    if (transitionResult.updatedStatus === "under_contract") {
      const existingContingencies = Array.isArray(project.contingencies) ? project.contingencies : [];
      if (existingContingencies.length === 0) {
        const baseDate = new Date(patchBody.psaExecutionDate || Date.now());
        updates.contingencies = [
          {
            id: `ctg-${projectId}-insp`,
            type: 'inspection',
            label: 'Property & Structural Inspection Contingency',
            deadline: new Date(baseDate.getTime() + (patchBody.contingencyDeadlines?.inspectionDays ?? 10) * 86400000).toISOString(),
            status: 'open',
          },
          {
            id: `ctg-${projectId}-fin`,
            type: 'financing',
            label: 'Commercial Debt Financing Contingency',
            deadline: new Date(baseDate.getTime() + (patchBody.contingencyDeadlines?.financingDays ?? 21) * 86400000).toISOString(),
            status: 'open',
          },
          {
            id: `ctg-${projectId}-appr`,
            type: 'appraisal',
            label: 'Lender Appraisal Valuation Contingency',
            deadline: new Date(baseDate.getTime() + (patchBody.contingencyDeadlines?.appraisalDays ?? 14) * 86400000).toISOString(),
            status: 'open',
          },
        ];
      }
    }

    if (!deps.updateProject) {
      return jsonResponse(500, { error: "Project updater not configured" });
    }

    const updatedProject = await deps.updateProject(projectId, updates);

    if (projectOrg) {
      await recordAuthzAuditEvent({
        organizationId: projectOrg,
        projectId,
        actorUid: auth.uid,
        actorRole: callerRole,
        action: 'project.stage_transitioned',
        targetType: 'project',
        targetId: projectId,
        fromState: { acquisitionStatus: currentStatus },
        toState: { acquisitionStatus: transitionResult.updatedStatus },
      }).catch(() => undefined);
    }

    if (transitionResult.updatedStatus === "under_contract" && deps.scheduleAlerts) {
      const allContingencies = updates.contingencies || (project.contingencies as any[]) || [];
      const projectAddress = (project.address as string) || (project.name as string);
      const ianaTimezone = (project.ianaTimezone as string) || undefined;
      await deps.scheduleAlerts(projectId, allContingencies as any[], projectAddress, ianaTimezone);
    }

    return jsonResponse(200, {
      success: true,
      projectId,
      currentStatus: transitionResult.updatedStatus,
      autoGeneratedTasks: transitionResult.autoGeneratedTasks ?? [],
      deadRecord: transitionResult.deadRecord,
      project: updatedProject,
    });
  } catch (error: unknown) {
    const message = error instanceof Error ? error.message : "Unknown error";
    console.error("[Project Acquisition Status Error]:", message);
    return jsonResponse(500, { error: "Failed to update acquisition status", details: message });
  }
}
