import type {
  ProjectWorkspace,
  ProjectTaskList,
  AcquisitionTask,
  ProjectCardColumn,
  ProjectHillChartItem,
  ProjectScheduleEvent,
  ProjectMessageTopic,
  LegacyProjectPhase,
} from './types';
import {
  ACQUISITION_CONVERSATIONAL_STEPS,
  FUND_CONVERSATIONAL_STEPS,
  HOLD_CONVERSATIONAL_STEPS,
  EXIT_CONVERSATIONAL_STEPS,
  type ConversationalStep,
} from './reil-conversational-steps';
import { newProjectItemId } from './project-access';

export interface InitializeProjectToolsOptions {
  projectId: string;
  propertyName: string;
  address: string;
  purchasePrice?: number;
  rehabBudget?: number;
  estimatedARV?: number | null;
  grossRentMonthly?: number;
  strategy?: string;
  creatorUid: string;
  creatorName?: string;
  teamMembers?: Array<{ uid?: string; id?: string; name: string; role: string; email?: string }>;
  targetContractDate?: string;
  targetClosingDate?: string;
  inspectionDays?: number;
  financingDays?: number;
}

/**
 * Initializes the full suite of Basecamp-style collaboration tools for a Project
 * directly mapped to the Real Estate Investment LifeCycle (REIL):
 * 1. To-do Lists: 4 phase lists with initial tasks seeded from conversational steps
 * 2. Card Table (The REIL): 4 columns with underwriting and key diligence cards
 * 3. Hill Chart: 4 items (one per REIL phase) to track trajectory
 * 4. Schedule: Target contract, inspection, financing and closing dates
 * 5. Message Board: Initial Kickoff announcement topic
 */
export function initializeProjectTools(
  options: InitializeProjectToolsOptions,
): Partial<ProjectWorkspace> {
  const {
    projectId,
    propertyName,
    address,
    purchasePrice = 0,
    rehabBudget = 0,
    estimatedARV = null,
    strategy = 'Fix & Flip',
    creatorUid,
    creatorName = 'Lead Underwriter',
    teamMembers = [],
    targetContractDate,
    targetClosingDate,
    inspectionDays = 14,
    financingDays = 21,
  } = options;

  const now = new Date().toISOString();

  // Find team member by role or fallback
  const findMemberForRole = (role: string) => {
    return teamMembers.find(
      (m) => m.role.toLowerCase() === role.toLowerCase() || m.role.toLowerCase().includes(role.toLowerCase()),
    );
  };

  // 1. To-do Lists: 4 Phase Lists
  const taskLists: ProjectTaskList[] = [
    { id: `tl-acq-${projectId}`, title: 'Acquisition & Underwriting', phase: 'acquisition', createdAt: now },
    { id: `tl-fund-${projectId}`, title: 'Funding & Capital Stack', phase: 'purchase', createdAt: now },
    { id: `tl-hold-${projectId}`, title: 'Hold & Value-Add Operations', phase: 'hold', createdAt: now },
    { id: `tl-exit-${projectId}`, title: 'Exit & Disposition', phase: 'exit', createdAt: now },
  ];

  // Map initial steps to tasks for each phase
  const tasks: AcquisitionTask[] = [];

  const addPhaseTasks = (
    steps: ConversationalStep[],
    listId: string,
    phase: LegacyProjectPhase,
    maxSteps: number = 3,
  ) => {
    for (const step of steps.slice(0, maxSteps)) {
      const matchedMember = findMemberForRole(step.defaultRole);
      const assigneeUid = matchedMember ? (matchedMember.uid || matchedMember.id) : undefined;
      const assigneeName = matchedMember ? matchedMember.name : step.defaultRole;

      tasks.push({
        id: `tsk-${step.id}-${projectId}`,
        projectId,
        title: step.title,
        listId,
        status: 'pending',
        isAutoGenerated: true,
        phase,
        notes: `${step.conversationalQuestion}\n\nWhy this matters: ${step.whyThisMatters}`,
        assigneeUid,
        assigneeName,
        assignedTo: assigneeName,
        assignedToUid: assigneeUid,
        vendorVisible: false,
        subtasks: step.requiredDocuments.map((doc, idx) => ({
          id: `sub-${step.id}-${idx}`,
          title: `Obtain / verify: ${doc}`,
          completed: false,
        })),
      });
    }
  };

  addPhaseTasks(ACQUISITION_CONVERSATIONAL_STEPS, taskLists[0]!.id, 'acquisition', 4);
  addPhaseTasks(FUND_CONVERSATIONAL_STEPS, taskLists[1]!.id, 'purchase', 3);
  addPhaseTasks(HOLD_CONVERSATIONAL_STEPS, taskLists[2]!.id, 'hold', 3);
  addPhaseTasks(EXIT_CONVERSATIONAL_STEPS, taskLists[3]!.id, 'exit', 2);

  // 2. The REIL Card Table: 4 Lifecycle Columns
  const cardColumns: ProjectCardColumn[] = [
    {
      id: 'col-acq',
      title: 'Acquisition & Underwriting',
      cards: [
        {
          id: `crd-underwrite-${projectId}`,
          title: 'Deal Calculator Underwriting Pro-Forma',
          description: `Price: $${purchasePrice.toLocaleString()} | Rehab: $${rehabBudget.toLocaleString()} | ARV: ${estimatedARV ? `$${estimatedARV.toLocaleString()}` : 'TBD'}. Verified baseline assumptions.`,
          columnId: 'col-acq',
          priority: 'high',
          vendorVisible: false,
        },
        {
          id: `crd-loi-${projectId}`,
          title: 'Executed Purchase & Sale Agreement (PSA)',
          description: 'Lock inspection contingency timelines and earnest money deposit terms with title escrow.',
          columnId: 'col-acq',
          priority: 'high',
          vendorVisible: false,
        },
      ],
    },
    {
      id: 'col-fund',
      title: 'Fund',
      cards: [
        {
          id: `crd-emd-${projectId}`,
          title: 'Wire Earnest Money Deposit (EMD)',
          description: 'Deliver initial escrow deposit to title company before contractual cutoff.',
          columnId: 'col-fund',
          priority: 'high',
          vendorVisible: false,
        },
        {
          id: `crd-loan-${projectId}`,
          title: 'Lender Term Sheet & Clear to Close',
          description: 'Lock debt terms, submit Phase I/appraisal clearances, and review final settlement statement.',
          columnId: 'col-fund',
          priority: 'high',
          vendorVisible: false,
        },
      ],
    },
    {
      id: 'col-hold',
      title: 'Hold',
      cards: [
        {
          id: `crd-scope-${projectId}`,
          title: 'Contractor Scope Lock & Utilities Transfer',
          description: 'Transfer electric/water utilities, set lockbox access, and execute contractor agreement.',
          columnId: 'col-hold',
          priority: 'medium',
          vendorVisible: true,
        },
      ],
    },
    {
      id: 'col-exit',
      title: 'Exit',
      cards: [
        {
          id: `crd-exit-${projectId}`,
          title: 'Disposition Strategy & Broker Engagement',
          description: `Target disposition model: ${strategy}. Calibrate listing pricing against completed rehab scope.`,
          columnId: 'col-exit',
          priority: 'low',
          vendorVisible: false,
        },
      ],
    },
  ];

  // 3. Hill Chart: 4 items (one per REIL phase)
  const hillChartItems: ProjectHillChartItem[] = [
    {
      id: `hill-acq-${projectId}`,
      scopeName: 'Phase 1: Acquisition Diligence & PSA Lock',
      position: 65, // downhill - executing on contract
      phase: 'acquisition',
      statusNotes: 'Deal intake complete, pro-forma calibrated in Deal Calculator.',
      updatedAt: now,
    },
    {
      id: `hill-fund-${projectId}`,
      scopeName: 'Phase 2: Capital Stack & Debt Placement',
      position: 35, // uphill - securing lender term sheet
      phase: 'purchase',
      statusNotes: 'Reviewing debt covenants and earnest money deposit escrow.',
      updatedAt: now,
    },
    {
      id: `hill-hold-${projectId}`,
      scopeName: 'Phase 3: Value-Add Execution & Renovation',
      position: 15, // uphill - scoping contractors
      phase: 'hold',
      statusNotes: 'Contractor bids in progress, utility transfer scheduled.',
      updatedAt: now,
    },
    {
      id: `hill-exit-${projectId}`,
      scopeName: 'Phase 4: Exit & Capital Return',
      position: 5, // uphill - planned
      phase: 'exit',
      statusNotes: `Target disposition path: ${strategy}.`,
      updatedAt: now,
    },
  ];

  // 4. Schedule Events
  const scheduleEvents: ProjectScheduleEvent[] = [];
  if (targetContractDate) {
    scheduleEvents.push({
      id: `evt-contract-${projectId}`,
      title: 'Target PSA Contract Date',
      date: targetContractDate,
      category: 'closing',
      phase: 'acquisition',
      isHardDate: true,
      source: 'manual',
      notes: 'Bilateral execution of Purchase & Sale Agreement.',
    });
  }

  // Inspection date
  const inspectionDate = new Date(Date.now() + inspectionDays * 86400000).toISOString().split('T')[0]!;
  scheduleEvents.push({
    id: `evt-inspection-${projectId}`,
    title: 'Physical & Environmental Inspection Period Ends',
    date: inspectionDate,
    category: 'inspection',
    phase: 'acquisition',
    isHardDate: true,
    source: 'manual',
    notes: `${inspectionDays}-day inspection contingency deadline.`,
  });

  // Financing date
  const financingDate = new Date(Date.now() + financingDays * 86400000).toISOString().split('T')[0]!;
  scheduleEvents.push({
    id: `evt-financing-${projectId}`,
    title: 'Loan Approval & Financing Contingency Deadline',
    date: financingDate,
    category: 'contingency',
    phase: 'purchase',
    isHardDate: true,
    source: 'manual',
    notes: `${financingDays}-day financing contingency cutoff.`,
  });

  if (targetClosingDate) {
    scheduleEvents.push({
      id: `evt-closing-${projectId}`,
      title: 'Target Settlement & Deed Recordation',
      date: targetClosingDate,
      category: 'closing',
      phase: 'purchase',
      isHardDate: true,
      source: 'manual',
      notes: 'Escrow funding, loan disbursement, and county recording.',
    });
  }

  // 5. Message Board: Initial Kickoff Topic
  const messageTopics: ProjectMessageTopic[] = [
    {
      id: newProjectItemId('top'),
      title: `Kickoff: ${propertyName || address}`,
      category: 'announcement',
      content: `Welcome to the project workspace for ${propertyName || address}.\n\nUnderwriting highlights:\n- Strategy: ${strategy}\n- Purchase Price: $${purchasePrice.toLocaleString()}\n- Estimated Rehab: $${rehabBudget.toLocaleString()}\n- Target ARV: ${estimatedARV ? `$${estimatedARV.toLocaleString()}` : 'TBD'}\n\nCollaboration tools (To-dos, The REIL board, Schedule, Campfire chat, Docs & Files) are initialized across all four phases of the Real Estate Investment LifeCycle (REIL).`,
      author: {
        id: creatorUid,
        name: creatorName,
        role: 'Project Lead',
      },
      phase: 'acquisition',
      createdAt: now,
      updatedAt: now,
      vendorVisible: false,
      comments: [],
    },
  ];

  return {
    taskLists,
    tasks,
    cardColumns,
    hillChartItems,
    scheduleEvents,
    messageTopics,
    campfireMessages: [],
    checkInQuestions: [
      {
        id: newProjectItemId('chk'),
        prompt: 'What are the top diligence priorities or contingency items for this deal this week?',
        frequency: 'weekly',
        assignedRoles: ['Lead Underwriter', 'Acquisitions Director'],
        createdAt: now,
        responses: [],
      },
    ],
  };
}
