import { newProjectItemId } from './project-access';
import type {
  ProjectWorkspace,
  AcquisitionTask,
  ProjectScheduleEvent,
  ProjectCampfireMessage,
} from './types';

export interface CommandProcessResult {
  messageText: string;
  createdTask?: AcquisitionTask;
  createdEvent?: ProjectScheduleEvent;
  systemNotice?: string;
}

/**
 * Parses and executes Basecamp-style campfire slash commands:
 * - /todo <title> [@name] [due YYYY-MM-DD]
 * - /date <YYYY-MM-DD> <title>
 * - /ping [@role or @name] <note>
 */
export function processCampfireCommand(
  rawText: string,
  project: ProjectWorkspace,
  author: { id: string; name: string; role: string },
): CommandProcessResult {
  const trimmed = rawText.trim();
  const now = new Date().toISOString();

  // 1. /todo command
  if (trimmed.startsWith('/todo ')) {
    const todoPayload = trimmed.slice(6).trim();
    if (!todoPayload) return { messageText: rawText };

    // Extract due date if present (e.g. "due 2026-08-25")
    const dueMatch = todoPayload.match(/\bdue\s+(\d{4}-\d{2}-\d{2})\b/i);
    const dueDate = dueMatch ? dueMatch[1] : undefined;

    // Clean title without the due date clause
    const titleWithoutDue = dueDate
      ? todoPayload.replace(/\bdue\s+\d{4}-\d{2}-\d{2}\b/i, '').trim()
      : todoPayload;

    // Extract @assignee if present
    const atMatch = titleWithoutDue.match(/@([\w.-]+)/);
    let assigneeUid: string | undefined;
    let assigneeName: string | undefined;

    if (atMatch) {
      const queryName = atMatch[1]?.toLowerCase();
      const matched = (project.teamMembers || []).find((m: any) =>
        m.name?.toLowerCase().includes(queryName) || m.role?.toLowerCase().includes(queryName)
      );
      if (matched) {
        assigneeUid = matched.uid || matched.id;
        assigneeName = matched.name;
      }
    }

    const title = titleWithoutDue.replace(/@[\w.-]+/, '').trim() || 'Untitled task';
    const listId = project.taskLists?.[0]?.id || `tl-${project.id}`;

    const task: AcquisitionTask = {
      id: newProjectItemId('tsk'),
      projectId: project.id,
      title,
      listId,
      status: 'pending',
      isAutoGenerated: false,
      phase: project.currentPhase || 'acquisition',
      assigneeUid,
      assigneeName,
      assignedTo: assigneeName,
      assignedToUid: assigneeUid,
      dueDate,
      vendorVisible: false,
      subtasks: [],
    };

    return {
      messageText: `📋 Created task: "${title}"${dueDate ? ` (Due: ${dueDate})` : ''}${assigneeName ? ` - Assigned to ${assigneeName}` : ''}`,
      createdTask: task,
      systemNotice: `Created to-do "${title}" from Campfire command`,
    };
  }

  // 2. /date command
  if (trimmed.startsWith('/date ')) {
    const parts = trimmed.slice(6).trim().split(/\s+/);
    const dateCandidate = parts[0];
    const eventTitle = parts.slice(1).join(' ').trim();

    if (dateCandidate && /^\d{4}-\d{2}-\d{2}$/.test(dateCandidate) && eventTitle) {
      const event: ProjectScheduleEvent = {
        id: newProjectItemId('evt'),
        title: eventTitle,
        date: dateCandidate,
        category: 'milestone',
        phase: project.currentPhase || 'acquisition',
        isHardDate: false,
        source: 'manual',
        notes: `Created from Campfire by ${author.name}`,
      };

      return {
        messageText: `📅 Added milestone: "${eventTitle}" on ${dateCandidate}`,
        createdEvent: event,
        systemNotice: `Added milestone "${eventTitle}" to project schedule`,
      };
    }
  }

  // 3. /ping command
  if (trimmed.startsWith('/ping ')) {
    const pingContent = trimmed.slice(6).trim();
    return {
      messageText: `🔔 PING: ${pingContent}`,
      systemNotice: 'Ping sent to team',
    };
  }

  return { messageText: rawText };
}
